/* R³∞ Quantum Cube graph layer — Graphify bridge v1.0 */
(function () {
  'use strict';

  const base = window.CUBO_OPERE_DATA;
  if (!base || !Array.isArray(base.nodes) || !Array.isArray(base.links)) return;

  base.links.forEach(link => {
    if (!link.evidence) link.evidence = link.confidence || 'DECLARED';
    if (!link.confidence) link.confidence = link.evidence;
    if (!link.sourceSystem) link.sourceSystem = 'Cubo Quantico / R³∞';
    if (!link.state) link.state = 'OBSERVED';
  });

  base.nodes.forEach(node => {
    if (typeof node.credit === 'string') {
      node.credit = node.credit.replace(/Raffaello Cardarelli/g, 'Raffaello Cantarelli');
    }
  });

  const extra = window.CUBO_GRAPHIFY_DATA;
  if (!extra || !Array.isArray(extra.nodes) || !Array.isArray(extra.links)) {
    base.meta = base.meta || {};
    base.meta.graphLayer = {
      version: '1.0',
      graphify: false,
      policy: 'Graphify is a sensor, not an authority.'
    };
    return;
  }

  const nodeIds = new Set(base.nodes.map(node => node.id));
  extra.nodes.forEach(node => {
    if (!node || !node.id || nodeIds.has(node.id)) return;
    base.nodes.push(node);
    nodeIds.add(node.id);
  });

  const endpoint = value => (value && typeof value === 'object') ? value.id : value;
  const edgeKey = link => [
    endpoint(link.source),
    endpoint(link.target),
    link.type || link.relation || 'related',
    link.sourceSystem || ''
  ].join('|');

  const edgeKeys = new Set(base.links.map(edgeKey));
  extra.links.forEach(link => {
    if (!link) return;
    const source = endpoint(link.source);
    const target = endpoint(link.target);
    if (!nodeIds.has(source) || !nodeIds.has(target)) return;

    const normalized = Object.assign({}, link, {
      source,
      target,
      type: link.type || link.relation || 'related',
      confidence: String(link.confidence || link.evidence || 'AMBIGUOUS').toUpperCase(),
      evidence: String(link.evidence || link.confidence || 'AMBIGUOUS').toUpperCase(),
      sourceSystem: link.sourceSystem || 'Graphify',
      state: link.state || 'OBSERVED'
    });

    const key = edgeKey(normalized);
    if (edgeKeys.has(key)) return;
    base.links.push(normalized);
    edgeKeys.add(key);
  });

  base.meta = base.meta || {};
  base.meta.graphLayer = {
    version: '1.0',
    graphify: true,
    importedNodes: extra.nodes.length,
    importedLinks: extra.links.length,
    policy: {
      EXTRACTED: 'observed directly in source',
      INFERRED: 'inference; not canonical fact',
      AMBIGUOUS: 'manual review required',
      DECLARED: 'curated relationship already present in the Cubo',
      POSSIBLE: 'future branch generated by the Matrice dei Possibili'
    }
  };
})();
